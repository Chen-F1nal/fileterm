#[cfg(any(target_os = "linux", target_os = "windows"))]
use tauri::image::Image;
use tauri::AppHandle;
#[cfg(any(target_os = "linux", target_os = "windows"))]
use tauri::Manager;

pub(crate) fn icon_bytes(variant: &str) -> &'static [u8] {
    match variant {
        "material" => include_bytes!("../../src/renderer/assets/app-icons/dock-material.png"),
        "clean" => include_bytes!("../../src/renderer/assets/app-icons/dock-clean.png"),
        _ => include_bytes!("../../src/renderer/assets/app-icons/dock-classic.png"),
    }
}

#[cfg(any(target_os = "linux", target_os = "windows"))]
pub(crate) fn window_icon_image(variant: &str) -> Result<Image<'static>, String> {
    Image::from_bytes(icon_bytes(variant)).map_err(|error| error.to_string())
}

#[cfg(target_os = "linux")]
fn tray_icon_bytes(variant: &str) -> &'static [u8] {
    match variant {
        "material" => include_bytes!("../icons/app-tray/tray-linux-material-32.png"),
        "clean" => include_bytes!("../icons/app-tray/tray-linux-clean-32.png"),
        _ => include_bytes!("../icons/app-tray/tray-linux-classic-32.png"),
    }
}

#[cfg(target_os = "windows")]
fn tray_icon_bytes(variant: &str) -> &'static [u8] {
    match variant {
        "material" => include_bytes!("../icons/app-tray/tray-windows-material-256.png"),
        "clean" => include_bytes!("../icons/app-tray/tray-windows-clean-256.png"),
        _ => include_bytes!("../icons/app-tray/tray-windows-classic-256.png"),
    }
}

#[cfg(any(target_os = "linux", target_os = "windows"))]
pub(crate) fn tray_icon_image(variant: &str) -> Result<Image<'static>, String> {
    Image::from_bytes(tray_icon_bytes(variant)).map_err(|error| error.to_string())
}

pub fn set_app_icon(app: &AppHandle, variant: &str) -> Result<(), String> {
    #[cfg(target_os = "macos")]
    crate::macos_icon::set_app_icon(app, variant)?;

    #[cfg(any(target_os = "linux", target_os = "windows"))]
    {
        let icon = window_icon_image(variant)?;
        for window in app.webview_windows().values() {
            window
                .set_icon(icon.clone())
                .map_err(|error| error.to_string())?;
        }

        if let Some(tray) = app.tray_by_id("main") {
            tray.set_icon(Some(tray_icon_image(variant)?))
                .map_err(|error| error.to_string())?;
        }
    }

    #[cfg(target_os = "linux")]
    set_linux_launcher_icon(app, variant)?;

    Ok(())
}

#[cfg(target_os = "linux")]
fn set_linux_launcher_icon(app: &AppHandle, variant: &str) -> Result<(), String> {
    use std::{fs, path::PathBuf};

    const MARKER: &str = "# Generated by FileTerm app icon settings.";
    let applications_dir = app
        .path()
        .data_dir()
        .map_err(|error| error.to_string())?
        .join("applications");
    let desktop_file = applications_dir.join("FileTerm.desktop");

    if variant == "classic" {
        // shortcut: desktop shells cache launcher icons; refresh the launcher if it stays stale.
        if fs::read_to_string(&desktop_file).is_ok_and(|contents| contents.starts_with(MARKER)) {
            fs::remove_file(desktop_file).map_err(|error| error.to_string())?;
        }
        return Ok(());
    }

    if desktop_file.exists()
        && !fs::read_to_string(&desktop_file).is_ok_and(|contents| contents.starts_with(MARKER))
    {
        return Err("a user-managed FileTerm launcher already exists".to_string());
    }

    let icon_path = app
        .path()
        .app_data_dir()
        .map_err(|error| error.to_string())?
        .join("app-icons")
        .join("launcher.png");
    let icon_directory = icon_path
        .parent()
        .ok_or_else(|| "unable to resolve the app icon directory".to_string())?;
    fs::create_dir_all(icon_directory).map_err(|error| error.to_string())?;
    fs::write(&icon_path, icon_bytes(variant)).map_err(|error| error.to_string())?;

    let executable = std::env::var_os("APPIMAGE")
        .map(PathBuf::from)
        .or_else(|| std::env::current_exe().ok())
        .ok_or_else(|| "unable to resolve the FileTerm executable path".to_string())?;
    let executable_path = executable.to_string_lossy();
    let executable = quote_desktop_exec_arg(&executable_path);
    let try_exec = escape_desktop_value(&executable_path);
    let icon_path = escape_desktop_value(&icon_path.to_string_lossy());
    let contents = format!(
        "{MARKER}\n[Desktop Entry]\nName=FileTerm\nComment=Remote terminal and file management workspace\nExec={executable} %U\nTryExec={try_exec}\nIcon={icon_path}\nTerminal=false\nType=Application\nCategories=Utility;Network;\nKeywords=SSH;SFTP;FTP;Terminal;\nStartupWMClass=fileterm\n"
    );

    fs::create_dir_all(&applications_dir).map_err(|error| error.to_string())?;
    let temporary_file = desktop_file.with_extension("desktop.tmp");
    fs::write(&temporary_file, contents).map_err(|error| error.to_string())?;
    fs::rename(temporary_file, desktop_file).map_err(|error| error.to_string())
}

#[cfg(any(target_os = "linux", test))]
fn quote_desktop_exec_arg(value: &str) -> String {
    format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('`', "\\`")
            .replace('$', "\\$")
            .replace('%', "%%")
    )
}

#[cfg(any(target_os = "linux", test))]
fn escape_desktop_value(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('\n', "\\n")
        .replace('\t', "\\t")
        .replace('\r', "\\r")
        .replace(' ', "\\s")
}

#[cfg(test)]
mod tests {
    use super::icon_bytes;

    #[test]
    fn each_app_icon_variant_is_an_rgba_png() {
        for variant in ["classic", "material", "clean"] {
            let bytes = icon_bytes(variant);
            assert_eq!(&bytes[..8], b"\x89PNG\r\n\x1a\n");
            assert_eq!(&bytes[12..16], b"IHDR");
            assert_eq!(bytes[24], 8);
            assert_eq!(bytes[25], 6);
        }
    }

    #[test]
    fn platform_tray_icon_assets_keep_native_sizes_and_rgba_format() {
        for (icon, size) in [
            (
                &include_bytes!("../icons/app-tray/tray-linux-classic-32.png")[..],
                32,
            ),
            (
                &include_bytes!("../icons/app-tray/tray-linux-material-32.png")[..],
                32,
            ),
            (
                &include_bytes!("../icons/app-tray/tray-linux-clean-32.png")[..],
                32,
            ),
            (
                &include_bytes!("../icons/app-tray/tray-windows-classic-256.png")[..],
                256,
            ),
            (
                &include_bytes!("../icons/app-tray/tray-windows-material-256.png")[..],
                256,
            ),
            (
                &include_bytes!("../icons/app-tray/tray-windows-clean-256.png")[..],
                256,
            ),
        ] {
            assert_eq!(&icon[..8], b"\x89PNG\r\n\x1a\n");
            assert_eq!(&icon[12..16], b"IHDR");
            assert_eq!(u32::from_be_bytes(icon[16..20].try_into().unwrap()), size);
            assert_eq!(u32::from_be_bytes(icon[20..24].try_into().unwrap()), size);
            assert_eq!(icon[24], 8, "tray PNGs must use 8-bit channels");
            assert_eq!(icon[25], 6, "tray PNGs must use RGBA pixels");
        }
    }

    #[test]
    fn desktop_entry_paths_escape_special_characters() {
        assert_eq!(
            super::quote_desktop_exec_arg("/home/a b/File\"Term`$%"),
            "\"/home/a b/File\\\"Term\\`\\$%%\""
        );
        assert_eq!(
            super::escape_desktop_value("/home/a b/File\\Term.png"),
            "/home/a\\sb/File\\\\Term.png"
        );
    }
}
