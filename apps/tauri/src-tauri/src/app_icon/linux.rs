use sha2::{Digest, Sha256};
use std::{fs, path::Path};

const MARKER: &str = "# Generated by FileTerm app icon settings.";
const DESKTOP_ENTRIES: [(&str, &str); 2] = [
    (
        "FileTerm.desktop",
        include_str!("../../linux/FileTerm.desktop"),
    ),
    (
        "com.fileterm.desktop.desktop",
        include_str!("../../linux/com.fileterm.desktop.desktop"),
    ),
];

#[cfg(target_os = "linux")]
pub(super) fn set_launcher_icon(app: &tauri::AppHandle, variant: &str) -> Result<(), String> {
    use tauri::Manager;

    // Development builds share preferences with the installed app, but must
    // never replace its launchers with a target/debug executable.
    if app.config().identifier != "com.fileterm.desktop" {
        return Ok(());
    }
    let current_exe = std::env::current_exe().map_err(|error| error.to_string())?;
    let executable = std::env::var_os("APPIMAGE")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| packaged_launcher(&current_exe));
    let desktop_dir = app.path().desktop_dir().ok();
    update_launcher_icons(
        &app.path()
            .data_dir()
            .map_err(|error| error.to_string())?
            .join("applications"),
        &app.path()
            .app_data_dir()
            .map_err(|error| error.to_string())?
            .join("app-icons"),
        desktop_dir.as_deref(),
        &executable,
        variant,
    )
}

fn packaged_launcher(current_exe: &Path) -> std::path::PathBuf {
    // Universal deb and pacman use a wrapper. Keep that public entry point,
    // including when running the Debian 11 private compatibility binary.
    match current_exe.to_str() {
        Some("/usr/lib/fileterm/fileterm" | "/usr/lib/fileterm/runtime/fileterm") => {
            "/usr/bin/fileterm".into()
        }
        _ => current_exe.into(),
    }
}

fn update_launcher_icons(
    applications_dir: &Path,
    icon_dir: &Path,
    desktop_dir: Option<&Path>,
    executable: &Path,
    variant: &str,
) -> Result<(), String> {
    // Preflight every ID before writing either: preserve all user-managed entries.
    for (name, _) in DESKTOP_ENTRIES {
        let path = applications_dir.join(name);
        match fs::read_to_string(&path) {
            Ok(contents) if !contents.starts_with(MARKER) => {
                return Err(format!(
                    "a user-managed FileTerm launcher already exists: {}",
                    path.display()
                ));
            }
            Err(error) if error.kind() != std::io::ErrorKind::NotFound => {
                return Err(error.to_string())
            }
            _ => {}
        }
    }
    let variant = match variant {
        "material" => "material",
        "clean" => "clean",
        _ => "classic",
    };
    let bytes = super::icon_bytes(variant);
    // Different variants and future artwork revisions need different paths so
    // GNOME/KDE cannot reuse an old decoded image for the same filename.
    let digest = format!("{:x}", Sha256::digest(bytes));
    let icon_path = icon_dir.join(format!("launcher-{variant}-{}.png", &digest[..16]));
    fs::create_dir_all(icon_dir).map_err(|error| error.to_string())?;
    fs::create_dir_all(applications_dir).map_err(|error| error.to_string())?;
    write_if_changed(&icon_path, bytes)?;

    let executable_value = executable.to_string_lossy();
    let mut exec = quote_desktop_exec_arg(&executable_value);
    // GIO validates the command before expanding %% and otherwise rejects
    // executables whose actual filename contains %. env defers that lookup
    // until after field expansion without introducing a shell.
    if executable_value.contains('%') {
        exec = format!("/usr/bin/env {exec}");
    }
    let try_exec = escape_desktop_value(&executable.to_string_lossy());
    let icon = escape_desktop_value(&icon_path.to_string_lossy());
    for (name, template) in DESKTOP_ENTRIES {
        let mut contents = format!("{MARKER}\n");
        for line in template.lines() {
            let line = if line.starts_with("Exec=") {
                format!("Exec={exec} %U")
            } else if line.starts_with("TryExec=") {
                format!("TryExec={try_exec}")
            } else if line.starts_with("Icon=") {
                format!("Icon={icon}")
            } else {
                line.to_string()
            };
            contents.push_str(&line);
            contents.push('\n');
        }
        // Always keep an explicit classic override as well: this repairs old
        // generated entries and prevents falling back to stale installed art.
        write_if_changed(&applications_dir.join(name), contents.as_bytes())?;
    }
    if let Some(desktop_dir) = desktop_dir {
        refresh_desktop_shortcuts(desktop_dir, &exec, icon_dir, &icon)?;
    }
    Ok(())
}

fn refresh_desktop_shortcuts(
    desktop_dir: &Path,
    executable: &str,
    icon_dir: &Path,
    icon: &str,
) -> Result<(), String> {
    let entries = match fs::read_dir(desktop_dir) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error.to_string()),
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path
            .extension()
            .is_none_or(|extension| extension != "desktop")
        {
            continue;
        }
        if fs::symlink_metadata(&path).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
            continue;
        }
        let Ok(contents) = fs::read_to_string(&path) else {
            continue;
        };
        let Some(updated) = update_desktop_shortcut(&contents, executable, icon_dir, icon) else {
            continue;
        };
        write_if_changed(&path, updated.as_bytes())?;
    }
    Ok(())
}

fn update_desktop_shortcut(
    contents: &str,
    executable: &str,
    icon_dir: &Path,
    icon: &str,
) -> Option<String> {
    let mut in_desktop_entry = false;
    let mut matches_executable = false;
    let mut icon_line = None;
    let mut lines: Vec<_> = contents.split_inclusive('\n').collect();
    let unquoted_executable = executable
        .strip_prefix('"')
        .and_then(|value| value.strip_suffix('"'))
        .filter(|value| !value.chars().any(char::is_whitespace));
    for (index, raw_line) in lines.iter().enumerate() {
        let line = raw_line.trim_end_matches(&['\r', '\n'][..]);
        if line.starts_with('[') {
            in_desktop_entry = line == "[Desktop Entry]";
        } else if in_desktop_entry {
            if let Some(value) = line.strip_prefix("Exec=") {
                matches_executable = [Some(executable), unquoted_executable]
                    .into_iter()
                    .flatten()
                    .any(|command| {
                        ["", " %U", " %u", " %F", " %f"]
                            .iter()
                            .any(|suffix| value == format!("{command}{suffix}"))
                    });
            } else if let Some(value) = line.strip_prefix("Icon=") {
                icon_line = Some((index, value));
            }
        }
    }
    let (index, current_icon) = icon_line?;
    if !matches_executable || !is_fileterm_icon(current_icon, icon_dir) {
        return None;
    }

    let line_ending = if lines[index].ends_with("\r\n") {
        "\r\n"
    } else if lines[index].ends_with('\n') {
        "\n"
    } else {
        ""
    };
    lines[index] = "";
    let mut updated = String::with_capacity(contents.len() + icon.len());
    for (line_index, line) in lines.into_iter().enumerate() {
        if line_index == index {
            updated.push_str("Icon=");
            updated.push_str(icon);
            updated.push_str(line_ending);
        } else {
            updated.push_str(line);
        }
    }
    Some(updated)
}

fn is_fileterm_icon(icon: &str, icon_dir: &Path) -> bool {
    if matches!(
        icon,
        "fileterm"
            | "fileterm.png"
            | "com.fileterm.desktop"
            | "/usr/share/pixmaps/fileterm.png"
            | "/usr/share/pixmaps/com.fileterm.desktop.png"
            | "/usr/share/icons/hicolor/32x32/apps/fileterm.png"
            | "/usr/share/icons/hicolor/128x128/apps/fileterm.png"
            | "/usr/share/icons/hicolor/256x256@2/apps/fileterm.png"
    ) {
        return true;
    }
    let path = Path::new(icon);
    path.parent() == Some(icon_dir)
        && path
            .file_name()
            .and_then(|name| name.to_str())
            .is_some_and(|name| name.starts_with("launcher-") && name.ends_with(".png"))
}

fn write_if_changed(path: &Path, bytes: &[u8]) -> Result<(), String> {
    if fs::read(path).is_ok_and(|current| current == bytes) {
        return Ok(());
    }
    let permissions = fs::metadata(path)
        .ok()
        .map(|metadata| metadata.permissions());
    let temporary = path.with_extension(format!("tmp-{}", std::process::id()));
    if let Err(error) = fs::write(&temporary, bytes) {
        let _ = fs::remove_file(&temporary);
        return Err(error.to_string());
    }
    if let Some(permissions) = permissions {
        if let Err(error) = fs::set_permissions(&temporary, permissions) {
            let _ = fs::remove_file(&temporary);
            return Err(error.to_string());
        }
    }
    if let Err(error) = fs::rename(&temporary, path) {
        let _ = fs::remove_file(temporary);
        return Err(error.to_string());
    }
    Ok(())
}

fn quote_desktop_exec_arg(value: &str) -> String {
    let quoted = format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('`', "\\`")
            .replace('$', "\\$")
            .replace('%', "%%")
    );
    // desktop-entry string escapes are decoded BEFORE Exec argument quoting.
    escape_desktop_value(&quoted)
}

fn escape_desktop_value(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('\n', "\\n")
        .replace('\t', "\\t")
        .replace('\r', "\\r")
}

